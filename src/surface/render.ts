/**
 * SURFACE-PARITY-001 — render the generated documentation section.
 *
 * Kept separate from `parity.ts` on purpose: this module reads only the matrix,
 * so the doc generator (`scripts/gen-surface-matrix.ts`) does not have to build
 * the Express app or load native DuckDB just to print a table.
 */

import { CAPABILITIES, type Capability, type SurfaceName } from "./capabilities.js";

export const GENERATED_BEGIN = "<!-- BEGIN GENERATED: surface-matrix -->";
export const GENERATED_END = "<!-- END GENERATED: surface-matrix -->";

const AREA_TITLES: Record<string, string> = {
  memory: "Memory records",
  namespace: "Namespaces",
  table: "Declared tables",
  query: "Query",
  s3: "S3 durability plane",
  ops: "Operations plane",
  metrics: "Metrics rollups",
  server: "Server lifecycle",
  mcp: "MCP transport",
  profiles: "Profiles",
  config: "Configuration",
  auth: "Auth & tokens",
  git: "Git identity",
  remote: "Storage remote",
  servers: "Saved servers",
  ssh: "SSH tunnels",
  embeddings: "Embeddings",
  session: "Session distillation",
};

function areaOf(cap: Capability): string {
  return cap.id.split(".")[0];
}

function surfaceCell(cap: Capability, surface: SurfaceName): string {
  const na = cap.na?.[surface];
  if (surface === "http") {
    if (cap.http?.length) return cap.http.map((route) => `\`${route}\``).join(", ");
  } else if (surface === "mcp") {
    if (cap.mcp?.length) return cap.mcp.map((tool) => `\`${tool}\``).join(", ");
  } else if (cap.cli) {
    const verb = cap.cli.sub ? `${cap.cli.verb} ${cap.cli.sub}` : cap.cli.verb;
    return `\`${verb}\``;
  }
  if (na) return `n/a — ${na}`;
  return "**pending**";
}

/** Surfaces the capability does not implement and has not ruled out. */
export function pendingSurfaces(cap: Capability): SurfaceName[] {
  const surfaces: SurfaceName[] = ["cli", "http", "mcp"];
  return surfaces.filter((surface) => {
    if (cap.na?.[surface]) return false;
    if (surface === "cli") return !cap.cli;
    return !cap[surface]?.length;
  });
}

/**
 * The generated section, markers included. Deterministic: the docs test
 * compares these bytes against the committed file, so the documented surface
 * cannot drift from the matrix and the matrix cannot drift from the code.
 */
export function renderSurfaceMarkdown(
  matrix: readonly Capability[] = CAPABILITIES,
): string {
  const lines: string[] = [];
  lines.push(GENERATED_BEGIN);
  lines.push(
    "<!-- Generated by scripts/gen-surface-matrix.ts from src/surface/capabilities.ts.",
  );
  lines.push("     Do not edit by hand: `pnpm docs:surface` rewrites this block, and");
  lines.push("     src/surface/parity.test.ts fails when it is stale. -->");
  lines.push("");

  const routeCount = new Set(matrix.flatMap((cap) => [...(cap.http ?? [])])).size;
  const toolCount = new Set(matrix.flatMap((cap) => [...(cap.mcp ?? [])])).size;
  const verbCount = new Set(
    matrix.flatMap((cap) => (cap.cli ? [cap.cli.verb] : [])),
  ).size;
  lines.push(
    `**${matrix.length} capabilities** cover ${routeCount} HTTP routes, ` +
      `${toolCount} MCP tools and ${verbCount} CLI verbs. ` +
      "`pending` means the surface does not implement it yet; `n/a` carries the " +
      "reason it never will.",
  );
  lines.push("");

  const areas = [...new Set(matrix.map(areaOf))];
  for (const area of areas) {
    lines.push(`### ${AREA_TITLES[area] ?? area}`);
    lines.push("");
    lines.push("| Capability | CLI | HTTP | MCP |");
    lines.push("| --- | --- | --- | --- |");
    for (const cap of matrix.filter((row) => areaOf(row) === area)) {
      lines.push(
        `| \`${cap.id}\` — ${cap.summary} | ${surfaceCell(cap, "cli")} | ` +
          `${surfaceCell(cap, "http")} | ${surfaceCell(cap, "mcp")} |`,
      );
    }
    lines.push("");
  }

  const gaps = matrix.filter((cap) => pendingSurfaces(cap).length > 0);
  lines.push("### Pending surfaces");
  lines.push("");
  if (gaps.length === 0) {
    lines.push("Every capability is on all three surfaces.");
  } else {
    for (const cap of gaps) {
      lines.push(`- \`${cap.id}\` — missing ${pendingSurfaces(cap).join(", ")}`);
    }
  }
  lines.push(GENERATED_END);
  return lines.join("\n");
}

/** Replace the generated block in `doc`, leaving hand-written prose alone. */
export function applyGeneratedBlock(doc: string, generated: string): string {
  const begin = doc.indexOf(GENERATED_BEGIN);
  const end = doc.indexOf(GENERATED_END);
  if (begin < 0 || end < 0 || end < begin) {
    throw new Error(
      `document has no ${GENERATED_BEGIN} … ${GENERATED_END} block to refresh`,
    );
  }
  return `${doc.slice(0, begin)}${generated}${doc.slice(end + GENERATED_END.length)}`;
}
